/* re-order: ① รู้จัก → ② ตัวอย่าง (steps whose text has “ตัวอย่าง”) → ③ the rest, in their original order */
(function applyLearnFirst() {
  const WEL = /^ยินดีต้อนรับสู่ <b>[^<]*<\/b>!\s*/;
  Object.entries(LRN).forEach(([id, [t, cards, sum, prefer]]) => {
    const L = LESSONS.find(x => x.id === +id); if (!L || L.learned) return;
    const old = L.teach, m = (old[0].t || '').match(WEL), welcome = m ? m[0] : '';
    const fix = st => { if (!WEL.test(st.t)) return st; const nt = st.t.replace(WEL, ''); return { ...st, t: nt, s: nt.replace(/<[^>]+>/g, '') }; };
    const ex = old.filter(st => /ตัวอย่าง/.test(st.t)); let rest = old.filter(st => !/ตัวอย่าง/.test(st.t)).map(fix);
    if (prefer) rest = [...rest.filter(st => prefer.test(st.t)), ...rest.filter(st => !prefer.test(st.t))];
    const intro = learnStep(welcome + t, (welcome + t).replace(/<[^>]+>/g, ''), cards, sum);
    L.teach = [...intro, ...ex.map(fix), ...rest]; L.learned = true;
  });
})();

